#!/usr/bin/env python3
"""Regenerate sw.js: list every site file and version the cache by content hash."""
import hashlib, os, json
root = os.path.dirname(os.path.abspath(__file__))
skip = {'sw.js', 'CNAME', '.nojekyll', 'gen-sw.py'}
files, h = [], hashlib.sha1()
for d, _, fs in sorted(os.walk(root)):
    for f in sorted(fs):
        rel = os.path.relpath(os.path.join(d, f), root).replace(os.sep, '/')
        if f in skip or 'banner-' in f:
            continue
        files.append(rel)
        h.update(rel.encode()); h.update(open(os.path.join(d, f), 'rb').read())
src = f"""/* Twin Queens offline cache. Generated by gen-sw.py; the version changes whenever a site file changes. */
const CACHE='tq-{h.hexdigest()[:10]}';
const FILES={json.dumps(['./'] + files, indent=1)};
self.addEventListener('install',e=>{{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(FILES)).then(()=>self.skipWaiting()))}});
self.addEventListener('activate',e=>{{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim()))}});
function withIsolationHeaders(response){{
  const headers=new Headers(response.headers);
  headers.set('Cross-Origin-Opener-Policy','same-origin');
  headers.set('Cross-Origin-Embedder-Policy','require-corp');
  return new Response(response.body,{{status:response.status,statusText:response.statusText,headers}});
}}
self.addEventListener('fetch',e=>{{
  if(e.request.method!=='GET')return;
  e.respondWith(caches.match(e.request,{{ignoreSearch:true}}).then(r=>r||fetch(e.request)).then(withIsolationHeaders));
}});
"""
open(os.path.join(root, 'sw.js'), 'w').write(src)
print(len(files), 'files cached')
